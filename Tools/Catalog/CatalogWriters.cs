using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace Altruist.Catalog;

public static class JsonCatalogWriter
{
    private static readonly JsonSerializerOptions Options = new()
    {
        WriteIndented = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        // The catalog is read by tools and people, not embedded in HTML: keep <, > and ' readable.
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
        Converters = { new JsonStringEnumConverter(JsonNamingPolicy.CamelCase) },
    };

    public static string Write(CapabilityCatalog catalog) => JsonSerializer.Serialize(catalog, Options).ReplaceLineEndings("\n") + "\n";
}

public static class MarkdownCatalogWriter
{
    private const string DocsSite = "https://altruist-docs.vercel.app";

    public static string Write(CapabilityCatalog catalog)
    {
        var text = new StringBuilder();
        text.Append($"# Altruist capabilities (v{catalog.Version})\n\n");
        text.Append("Generated by `Tools/Catalog` from the framework assemblies, their XML docs and `catalog/map.yml`. ");
        text.Append("Don't edit it by hand: change the map or the code, then run `dotnet run --project Tools/Catalog`. ");
        text.Append("The same content, for tools, is in `catalog/capabilities.json`.\n\n");
        text.Append("| Capability | What it is for |\n|---|---|\n");
        foreach (var capability in catalog.Capabilities)
            text.Append($"| [{capability.Spec.Title}](#{capability.Spec.Name}) | {Cell(FirstSentence(capability.Spec.Summary))} |\n");
        foreach (var capability in catalog.Capabilities)
            AppendCapability(text, capability);
        return text.ToString();
    }

    private static void AppendCapability(StringBuilder text, Capability capability)
    {
        var spec = capability.Spec;
        text.Append($"\n<a id=\"{spec.Name}\"></a>\n\n## {spec.Title}\n\n{spec.Summary}\n");
        AppendList(text, "Use it when", spec.Use);
        AppendList(text, "Don't use it when", spec.Avoid);
        var facts = new List<string>();
        if (spec.Packages.Count > 0) facts.Add($"**Packages:** {string.Join(", ", spec.Packages.Select(p => $"`{p}`"))}");
        if (spec.Docs.Count > 0) facts.Add($"**Docs:** {string.Join(", ", spec.Docs.Select(DocLink))}");
        if (facts.Count > 0) text.Append($"\n{string.Join(" · ", facts)}\n");
        if (spec.Example is not null) text.Append($"\n{spec.Example}\n");
        if (capability.KeyTypes.Count > 0)
        {
            text.Append("\n**Key types**\n\n");
            foreach (var type in capability.KeyTypes)
                text.Append($"- `{type.Type}`{Suffix(type.Summary)}\n");
        }
        AppendConfig(text, capability.Config);
        AppendServices(text, capability.Services);
        if (capability.Attributes.Count > 0)
        {
            text.Append("\n**Attributes**\n\n");
            foreach (var attribute in capability.Attributes)
                text.Append($"- `[{ShortAttributeName(attribute.Type)}]`{Suffix(attribute.Summary)}\n");
        }
    }

    private static void AppendList(StringBuilder text, string heading, IReadOnlyList<string> items)
    {
        if (items.Count == 0) return;
        text.Append($"\n**{heading}**\n\n");
        foreach (var item in items) text.Append($"- {item}\n");
    }

    private static void AppendConfig(StringBuilder text, IReadOnlyList<ConfigEntry> config)
    {
        if (config.Count == 0) return;
        text.Append("\n**Configuration**\n\n| Key | Type | Default | Notes |\n|---|---|---|---|\n");
        foreach (var entry in config)
        {
            var notes = new List<string>();
            if (entry.Description is not null) notes.Add(entry.Description);
            if (entry.Live) notes.Add("Follows config reloads.");
            if (entry.Gates.Count > 0) notes.Add($"Read only when {string.Join(" and ", entry.Gates)}.");
            if (entry.Origin == ConfigOrigin.Literal) notes.Add($"Read in `{entry.File}`.");
            text.Append($"| `{entry.Key}` | {Code(entry.Type)} | {Code(entry.Default)} | {Cell(string.Join(" ", notes))} |\n");
        }
    }

    private static void AppendServices(StringBuilder text, IReadOnlyList<ServiceEntry> services)
    {
        if (services.Count == 0) return;
        text.Append("\n**Services**\n\n");
        foreach (var service in services)
        {
            var role = service.Kind switch
            {
                ServiceKind.Service => service.Contracts[0] == service.Type ? "" : $" as `{service.Contracts[0]}`",
                ServiceKind.ConfigurationStep => " (configuration step)",
                ServiceKind.ConfigurationSection => $" (binds `{service.Contracts[0]}`)",
                ServiceKind.Portal => $" (portal at `{service.Contracts[0]}`)",
                ServiceKind.Controller => $" (HTTP at `{service.Contracts[0]}`)",
                _ => "",
            };
            var gates = service.Gates.Count == 0 ? "" : $" Only when {string.Join(" and ", service.Gates)}.";
            text.Append($"- `{service.Type}`{role}{Suffix(service.Summary)}{gates}\n");
        }
    }

    private static string DocLink(string path) => $"[{path}]({(path.StartsWith('/') ? DocsSite + path : path)})";

    private static string ShortAttributeName(string type)
    {
        var name = type.Split('.').Last();
        return name.EndsWith("Attribute", StringComparison.Ordinal) ? name[..^"Attribute".Length] : name;
    }

    private static string Suffix(string? summary) => summary is null ? "" : $": {FirstSentence(summary)}";

    private static string Code(string? value) => value is null ? "" : $"`{value.Replace("|", "\\|")}`";

    private static string Cell(string value) => value.Replace("|", "\\|").ReplaceLineEndings(" ");

    private static string FirstSentence(string text)
    {
        var end = text.IndexOf(". ", StringComparison.Ordinal);
        return end < 0 ? text : text[..(end + 1)];
    }
}
